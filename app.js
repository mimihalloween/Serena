const chat=document.getElementById("chat");
function esc(s){return s.replace(/[&<>"']/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;", "'":"&#039;"}[m]));}
function renderMessages(arr){
  chat.innerHTML="";
  for(const m of arr){
    if(m[0]==="day"){
      const d=document.createElement("div");
      d.className="day";
      d.textContent=m[1];
      chat.appendChild(d);
      continue;
    }
    const row=document.createElement("div");
    row.className="row "+m[0];
    row.innerHTML='<div><div class="bubble">'+esc(m[1])+'</div><div class="meta">'+m[2]+'</div></div>';
    chat.appendChild(row);
  }
}
function openChat(name){
  document.getElementById("inboxView").classList.remove("active");
  document.getElementById("chatView").classList.add("active");
  renderMessages(conversations[name]);
  const contact=name==="logan"?"Logan":"Violette";
  document.getElementById("contactName").textContent=contact;
  document.getElementById("contactStatus").textContent=name==="logan"?"Actif(ve) il y a 3 h":"Actif(ve) il y a 1 h";
  document.getElementById("contactAvatar").textContent=name==="logan"?"L":"V";
  document.getElementById("contactAvatar").className="avatar "+(name==="logan"?"logan":"violette");
  setTimeout(()=>window.scrollTo(0,document.body.scrollHeight),20);
}
function closeChat(){
  document.getElementById("chatView").classList.remove("active");
  document.getElementById("inboxView").classList.add("active");
}
window.openChat=openChat;
window.closeChat=closeChat;
